"""Measure the detector on eval/dataset.jsonl.

Scoring is strict: a prediction counts only if the TYPE and the exact character
span both match a labelled entity. ORGANIZATION is ignored on both sides because
it is context, not personal data, and is not redacted by default.

Also runs an ablation: the same data with layers switched off, to show what each
layer (checksums, context words, NER + name list) actually contributes.
"""
import json
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from vaultai.detector import PIIDetector  # noqa: E402

DATA = Path(__file__).with_name(sys.argv[1] if len(sys.argv) > 1 else "dataset.jsonl")
IGNORE = {"ORGANIZATION"}

CONFIGS = [
    ("Regex only", dict(use_checksums=False, use_context=False, use_ner=False, use_name_list=False)),
    ("+ checksums", dict(use_checksums=True, use_context=False, use_ner=False, use_name_list=False)),
    ("+ context words", dict(use_checksums=True, use_context=True, use_ner=False, use_name_list=False)),
    ("+ spaCy NER + name list (full)", dict(use_checksums=True, use_context=True, use_ner=True, use_name_list=True)),
]


def load():
    return [json.loads(l) for l in DATA.read_text().splitlines() if l.strip()]


def run(det, rows):
    tp, fp, fn = Counter(), Counter(), Counter()
    neg_with_fp = 0
    name_hits = Counter()
    for r in rows:
        gold = {(e["type"], e["start"], e["end"]) for e in r["entities"] if e["type"] not in IGNORE}
        pred = {(e.type, e.start, e.end) for e in det.detect(r["text"]) if e.type not in IGNORE}
        for g in gold & pred:
            tp[g[0]] += 1
        for p in pred - gold:
            fp[p[0]] += 1
        for g in gold - pred:
            fn[g[0]] += 1
        if r["tag"] == "hard_negative" and pred:
            neg_with_fp += 1
        if r["tag"] in ("seen_name", "unseen_name"):
            for g in gold:
                if g[0] == "PERSON":
                    name_hits[(r["tag"], g in pred)] += 1
    return tp, fp, fn, neg_with_fp, name_hits


def prf(tp, fp, fn):
    p = tp / (tp + fp) if tp + fp else 0.0
    r = tp / (tp + fn) if tp + fn else 0.0
    f = 2 * p * r / (p + r) if p + r else 0.0
    return p, r, f


def main():
    rows = load()
    n_neg = sum(r["tag"] == "hard_negative" for r in rows)
    n_spans = sum(len(r["entities"]) for r in rows)
    lines = [f"# VaultAI detection results: {DATA.name}\n",
             f"Test set: {len(rows)} sentences, {n_spans} labelled PII spans, {n_neg} hard-negative sentences "
             f"(order IDs, invoices, prices, versions, checksum-invalid 12-digit numbers). Strict match: type + exact span.\n",
             "## Ablation: what each layer adds\n",
             "| Configuration | Precision | Recall | F1 | Hard negatives wrongly flagged |",
             "|---|---|---|---|---|"]
    full = None
    for name, cfg in CONFIGS:
        det = PIIDetector(**cfg)
        tp, fp, fn, neg_fp, name_hits = run(det, rows)
        p, r, f = prf(sum(tp.values()), sum(fp.values()), sum(fn.values()))
        lines.append(f"| {name} | {p:.1%} | {r:.1%} | {f:.1%} | {neg_fp}/{n_neg} ({neg_fp / n_neg:.0%}) |")
        full = (tp, fp, fn, name_hits)

    tp, fp, fn, name_hits = full
    lines += ["\n## Full engine, per PII type\n", "| Type | Precision | Recall | F1 | Support |", "|---|---|---|---|---|"]
    for t in sorted(set(tp) | set(fn) | set(fp)):
        p, r, f = prf(tp[t], fp[t], fn[t])
        lines.append(f"| {t} | {p:.1%} | {r:.1%} | {f:.1%} | {tp[t] + fn[t]} |")

    def rec(tag):
        hit, miss = name_hits[(tag, True)], name_hits[(tag, False)]
        return f"{hit}/{hit + miss} ({hit / (hit + miss):.0%})" if hit + miss else "n/a"
    lines += ["\n## Person-name recall\n",
              f"- Names in the built-in Indian name list: {rec('seen_name')}",
              f"- Names the engine has never seen (spaCy only): {rec('unseen_name')}",
              "\nNote: the test set is synthetic (generated by eval/make_dataset.py with a fixed seed). "
              "Real-world text is messier, so treat these as a benchmark for comparing versions, not a guarantee."]
    out = "\n".join(lines)
    Path(__file__).with_name(DATA.stem + "_results.md").write_text(out + "\n")
    print(out)


if __name__ == "__main__":
    main()
